import fs from 'node:fs'
const p = 'src/math/rose.ts'
let s = fs.readFileSync(p, 'utf8')
if (s.charCodeAt(0) === 0xfeff) s = s.slice(1)
const rev = new Map()
const table = {
  0x80:0x20ac,0x82:0x201a,0x83:0x0192,0x84:0x201e,0x85:0x2026,0x86:0x2020,0x87:0x2021,
  0x88:0x02c6,0x89:0x2030,0x8a:0x0160,0x8b:0x2039,0x8c:0x0152,0x8e:0x017d,0x91:0x2018,
  0x92:0x2019,0x93:0x201c,0x94:0x201d,0x95:0x2022,0x96:0x2013,0x97:0x2014,0x98:0x02dc,
  0x99:0x2122,0x9a:0x0161,0x9b:0x203a,0x9c:0x0153,0x9e:0x017e,0x9f:0x0178,
}
for (const [b, c] of Object.entries(table)) rev.set(String.fromCharCode(c), Number(b))
const bytes = []
let bad = 0
for (const ch of s) {
  const c = ch.codePointAt(0)
  if (rev.has(ch)) bytes.push(rev.get(ch))
  else if (c < 0x100) bytes.push(c)
  else { bad++; bytes.push(0x3f) }
}
const buf = Buffer.from(bytes)
let out
try { out = new TextDecoder('utf-8', { fatal: true }).decode(buf) }
catch (e) { console.error('fallback', e.message); out = buf.toString('utf8') }
fs.writeFileSync(p, out, 'utf8')
console.log('bad chars:', bad, 'bytes:', buf.length, '-> chars:', out.length)
